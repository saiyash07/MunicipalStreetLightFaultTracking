-- =====================================================================
-- schema.sql  |  Municipal Street Light Fault Tracking  |  PostgreSQL
-- Run this FIRST, then seed.sql, then queries.sql.
-- Safe to re-run: it drops the old tables and rebuilds them.
-- =====================================================================

DROP TABLE IF EXISTS fault_verification CASCADE;
DROP TABLE IF EXISTS fault_assignment   CASCADE;
DROP TABLE IF EXISTS fault_report       CASCADE;
DROP TABLE IF EXISTS contractor_ward    CASCADE;
DROP TABLE IF EXISTS pole               CASCADE;
DROP TABLE IF EXISTS contractor         CASCADE;
DROP TABLE IF EXISTS ward               CASCADE;
DROP FUNCTION IF EXISTS trg_block_close_without_verification();
DROP FUNCTION IF EXISTS trg_block_verification_delete();
DROP FUNCTION IF EXISTS trg_check_contractor_serves_ward();

-- ---------------------------------------------------------------------
-- 1. WARD : a municipal ward, each with one ward engineer
-- ---------------------------------------------------------------------
CREATE TABLE ward (
    ward_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_name      VARCHAR(50) NOT NULL UNIQUE,
    zone           VARCHAR(10) NOT NULL
                   CHECK (zone IN ('North','South','East','West','Central')),
    engineer_name  VARCHAR(60) NOT NULL
);

-- ---------------------------------------------------------------------
-- 2. CONTRACTOR : electrical contractor
-- ---------------------------------------------------------------------
CREATE TABLE contractor (
    contractor_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_name  VARCHAR(60) NOT NULL UNIQUE,
    phone            CHAR(10)    NOT NULL UNIQUE
                     CHECK (phone ~ '^[0-9]{10}$')
);

-- ---------------------------------------------------------------------
-- 3. CONTRACTOR_WARD : which contractor serves which ward (many-to-many)
--    This is the "assigned by ward" part of the problem statement.
-- ---------------------------------------------------------------------
CREATE TABLE contractor_ward (
    contractor_id  INTEGER NOT NULL REFERENCES contractor(contractor_id),
    ward_id        INTEGER NOT NULL REFERENCES ward(ward_id),
    PRIMARY KEY (contractor_id, ward_id)
);

-- ---------------------------------------------------------------------
-- 4. POLE : a street light pole; belongs to exactly one ward
-- ---------------------------------------------------------------------
CREATE TABLE pole (
    pole_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pole_code     VARCHAR(12)  NOT NULL UNIQUE,
    ward_id       INTEGER      NOT NULL REFERENCES ward(ward_id),
    location      VARCHAR(100) NOT NULL,
    installed_on  DATE         NOT NULL
);

-- ---------------------------------------------------------------------
-- 5. FAULT_REPORT : a fault reported by a citizen on a pole
--    Only two states: OPEN (pending) and CLOSED.
--    CHECK below: CLOSED  <=>  closed_on is filled (and not before reported_on)
-- ---------------------------------------------------------------------
CREATE TABLE fault_report (
    fault_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pole_id      INTEGER      NOT NULL REFERENCES pole(pole_id),
    reported_by  VARCHAR(60)  NOT NULL,
    fault_type   VARCHAR(30)  NOT NULL
                 CHECK (fault_type IN ('Bulb not working','Flickering','Day burning',
                                       'Wiring fault','Pole damaged')),
    reported_on  DATE         NOT NULL DEFAULT CURRENT_DATE,
    status       VARCHAR(6)   NOT NULL DEFAULT 'OPEN'
                 CHECK (status IN ('OPEN','CLOSED')),
    closed_on    DATE,
    CONSTRAINT chk_status_closed_on CHECK (
        (status = 'OPEN'   AND closed_on IS NULL)
     OR (status = 'CLOSED' AND closed_on IS NOT NULL AND closed_on >= reported_on)
    )
);

-- ---------------------------------------------------------------------
-- 6. FAULT_ASSIGNMENT : a fault is handed to ONE contractor
--    UNIQUE(fault_id) = at most one assignment row per fault.
-- ---------------------------------------------------------------------
CREATE TABLE fault_assignment (
    assignment_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fault_id       INTEGER NOT NULL UNIQUE REFERENCES fault_report(fault_id),
    contractor_id  INTEGER NOT NULL REFERENCES contractor(contractor_id),
    assigned_on    DATE    NOT NULL
);

-- ---------------------------------------------------------------------
-- 7. FAULT_VERIFICATION : ward engineer's check that the repair was done
--    fault_id is both PK and FK  ->  at most one verification per fault.
-- ---------------------------------------------------------------------
CREATE TABLE fault_verification (
    fault_id     INTEGER PRIMARY KEY REFERENCES fault_report(fault_id),
    verified_by  VARCHAR(60) NOT NULL,
    verified_on  DATE        NOT NULL,
    remarks      VARCHAR(200)
);

-- =====================================================================
-- BUSINESS RULES THAT A PLAIN CHECK CONSTRAINT CANNOT EXPRESS
-- (they look at another table, so they are triggers)
-- =====================================================================

-- RULE 1: a fault cannot be CLOSED unless a verification row exists.
CREATE FUNCTION trg_block_close_without_verification() RETURNS trigger AS $$
BEGIN
    IF NEW.status = 'CLOSED'
       AND NOT EXISTS (SELECT 1 FROM fault_verification v
                       WHERE v.fault_id = NEW.fault_id) THEN
        RAISE EXCEPTION 'Fault % cannot be closed: it has not been verified', NEW.fault_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER fault_close_needs_verification
BEFORE INSERT OR UPDATE ON fault_report
FOR EACH ROW EXECUTE FUNCTION trg_block_close_without_verification();

-- RULE 2: the verification of an already-CLOSED fault cannot be deleted
--         (otherwise someone could delete it and leave a closed, unverified fault).
CREATE FUNCTION trg_block_verification_delete() RETURNS trigger AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM fault_report f
               WHERE f.fault_id = OLD.fault_id AND f.status = 'CLOSED') THEN
        RAISE EXCEPTION 'Cannot delete verification of closed fault %', OLD.fault_id;
    END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER verification_delete_guard
BEFORE DELETE ON fault_verification
FOR EACH ROW EXECUTE FUNCTION trg_block_verification_delete();

-- RULE 3: a fault may only be assigned to a contractor who serves that
--         fault's ward (fault -> pole -> ward must appear in contractor_ward).
CREATE FUNCTION trg_check_contractor_serves_ward() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM fault_report f
        JOIN pole p            ON p.pole_id = f.pole_id
        JOIN contractor_ward cw ON cw.ward_id = p.ward_id
        WHERE f.fault_id = NEW.fault_id
          AND cw.contractor_id = NEW.contractor_id
    ) THEN
        RAISE EXCEPTION 'Contractor % does not serve the ward of fault %',
                        NEW.contractor_id, NEW.fault_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER assignment_ward_check
BEFORE INSERT OR UPDATE ON fault_assignment
FOR EACH ROW EXECUTE FUNCTION trg_check_contractor_serves_ward();

-- Indexes on foreign keys we join / filter on most
CREATE INDEX idx_pole_ward        ON pole(ward_id);
CREATE INDEX idx_fault_pole       ON fault_report(pole_id);
CREATE INDEX idx_fault_status     ON fault_report(status);
CREATE INDEX idx_assign_contr     ON fault_assignment(contractor_id);
